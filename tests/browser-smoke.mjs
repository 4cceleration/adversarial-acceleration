import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const base = process.env.AA_TEST_BASE || 'http://127.0.0.1:4317';
const browser = await chromium.launch(process.env.CHROME_PATH ? { executablePath: process.env.CHROME_PATH } : {});
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const handle = `smoke_${Date.now().toString(36)}`;
try {
  await page.goto(base);
  await page.getByRole('button', { name: 'Abrir tu cuenta' }).click();
  await page.getByLabel('Usuario', { exact: true }).fill(handle);
  await page.getByLabel('Contraseña', { exact: true }).fill(`test-password-${Date.now()}!`);
  await page.getByRole('button', { name: 'Crear mi cuenta' }).click();
  await page.getByRole('heading', { name: 'Conexiones' }).waitFor();
  await page.getByLabel('Nombre de la conexión').fill('Prueba de navegador');
  await page.getByRole('button', { name: 'Crear token' }).click();
  await page.locator('#new-token code').waitFor();
  const token = await page.locator('#new-token code').innerText();
  assert.match(token, /^aa_live_/);
  await mkdir('.local', { recursive: true });
  await page.screenshot({ path: '.local/connections-desktop.png', mask: [page.locator('#new-token code')] });
  await page.getByRole('button', { name: 'Editar página', exact: false }).click();
  await page.getByLabel('Título de la página').fill('Prueba de navegador');
  await page.locator('#code-editor').fill('<main style="padding:80px"><h1>Contenido compartido</h1><button id="counter">0</button><p id="sandbox"></p></main>');
  await page.getByRole('button', { name: 'JavaScript', exact: true }).click();
  await page.locator('#code-editor').fill('let n=0;document.querySelector("#counter").onclick=()=>document.querySelector("#counter").textContent=++n;try{parent.document.body.innerHTML="unsafe"}catch(e){document.querySelector("#sandbox").textContent="Aislado"}');
  await page.getByRole('button', { name: 'Vista previa', exact: true }).click();
  await page.frameLocator('#preview-frame').getByRole('heading', { name: 'Contenido compartido' }).waitFor();
  await page.getByRole('button', { name: 'Publicar cambios' }).click();
  await page.frameLocator('#landing-frame').getByRole('heading', { name: 'Contenido compartido' }).waitFor();
  await page.frameLocator('#landing-frame').getByText('Aislado').waitFor();
  await page.frameLocator('#landing-frame').getByRole('button', { name: '0', exact: true }).click();
  await page.frameLocator('#landing-frame').getByRole('button', { name: '1', exact: true }).waitFor();
  const apiBase = await page.evaluate(() => window.AA_API_BASE);
  const landing = await (await fetch(apiBase + '/api/landing')).json();
  const update = await fetch(apiBase + '/api/landing', { method: 'PUT', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ expectedRevision: landing.revision, html: '<h1>Actualización externa</h1>', css: 'body{padding:64px}', js: '' }) });
  assert.equal(update.status, 200);
  await page.frameLocator('#landing-frame').getByRole('heading', { name: 'Actualización externa' }).waitFor({ timeout: 15000 });
  const next = await update.json();
  const clear = await fetch(apiBase + '/api/landing/clear', { method: 'POST', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, body: JSON.stringify({ expectedRevision: next.revision }) });
  assert.equal(clear.status, 200);
  await page.getByRole('button', { name: 'Abrir tu cuenta' }).click();
  await page.getByRole('button', { name: 'Conexiones', exact: false }).click();
  page.on('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Revocar', exact: true }).click();
  await page.getByText('Sin tokens activos', { exact: false }).waitFor();
  await page.getByRole('button', { name: 'Mi cuenta', exact: false }).click();
  await page.getByRole('button', { name: 'Cerrar sesión', exact: true }).click();
  await page.getByRole('button', { name: 'Entrar', exact: false }).last().waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: '.local/login-mobile.png' });
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
  assert.equal(overflow, false);
  assert.deepEqual(errors, []);
  console.log('Browser OK: registration, token, preview, sandbox, publish, live API update, revoke, logout, mobile.');
  console.log(`Temporary test account: ${handle}`);
} finally { await browser.close(); }
